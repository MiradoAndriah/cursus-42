#include "codexion.h"

int	main(int ac, char **av)
{
	t_sim	sim;

	memset(&sim, 0, sizeof(t_sim));
	if (parsing(ac, av, &sim.config))
		return (1);
	if (init_sim(&sim))
		return (1);
	run_sim(&sim);
	cleanup_sim(&sim);
	return (0);
}
